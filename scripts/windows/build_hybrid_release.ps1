function Run-Step([string]$Name, [scriptblock]$Action) {
  Write-Host "`n=== $Name ===" -ForegroundColor Cyan
  $global:LASTEXITCODE = 0
  & $Action
  if (!$?) { throw "$Name failed." }
  if ($LASTEXITCODE -ne 0) { throw "$Name failed with code $LASTEXITCODE" }
}

if (!$SkipFfmpegDownload) {
  if ([bool]$env:HIGHLIGHT_STUDIO_FFMPEG_URL -xor [bool]$env:HIGHLIGHT_STUDIO_FFMPEG_SHA256) {
    throw "Custom FFmpeg source requires both HIGHLIGHT_STUDIO_FFMPEG_URL and HIGHLIGHT_STUDIO_FFMPEG_SHA256."
  }
  $FfmpegArgs = @{ Force = $true }
  if ($env:HIGHLIGHT_STUDIO_FFMPEG_URL) {
    $FfmpegArgs.Url = $env:HIGHLIGHT_STUDIO_FFMPEG_URL
    $FfmpegArgs.Sha256 = $env:HIGHLIGHT_STUDIO_FFMPEG_SHA256
  }
  Run-Step "Prepare checksum-pinned bundled FFmpeg" { & (Join-Path $PSScriptRoot "fetch_ffmpeg.ps1") @FfmpegArgs }
}
if (!$SkipTwitchDownloaderDownload) {
  Run-Step "Prepare checksum-pinned TwitchDownloaderCLI" { & (Join-Path $PSScriptRoot "fetch_twitchdownloader.ps1") -Force }
}

if (!$InstallerOnly) {
  if (!(Test-Path $BuildVenv)) {
    Run-Step "Create production build virtual environment" { python -m venv $BuildVenv }
  }
  $Python = Join-Path $BuildVenv "Scripts\python.exe"
  Run-Step "Upgrade production build pip" { & $Python -m pip install --upgrade pip }
  Run-Step "Install production build dependencies" { & $Python -m pip install -r backend\requirements-build.txt }

  Run-Step "Install frontend dependencies" { npm --prefix frontend ci }
  Run-Step "Build frontend" { npm --prefix frontend run build }
  if (!$SkipTests) {
    if (!(Test-Path $TestVenv)) {
      Run-Step "Create test virtual environment" { python -m venv $TestVenv }
    }
    $TestPython = Join-Path $TestVenv "Scripts\python.exe"
    Run-Step "Upgrade test environment pip" { & $TestPython -m pip install --upgrade pip }
    Run-Step "Install Python test dependencies" { & $TestPython -m pip install -r backend\requirements-dev.txt }
    Run-Step "Backend tests" {
      $PytestLog = Join-Path $env:RUNNER_TEMP "highlight-studio-pytest.log"
      & $TestPython -m pytest -q 2>&1 | Tee-Object -FilePath $PytestLog
      $PytestExitCode = $LASTEXITCODE
      if ($PytestExitCode -ne 0) {
        $PytestTail = (Get-Content $PytestLog -Tail 100) -join "`n"
        $PytestAnnotation = $PytestTail.Replace("%", "%25").Replace("`r", "%0D").Replace("`n", "%0A")
        Write-Output "::error title=Backend test failure details::$PytestAnnotation"
        throw "Backend tests failed with code $PytestExitCode"
      }
    }
    Run-Step "Python lint" { & $TestPython -m ruff check backend tests tools }
    Run-Step "Python compileall" { & $TestPython -m compileall -q backend tools tests }
    Run-Step "Architecture audit" { & $TestPython tools\quality\architecture_audit.py }
    Run-Step "Frontend tests" {
      $FrontendTestLog = Join-Path $env:RUNNER_TEMP "highlight-studio-frontend-tests.log"
      npm --prefix frontend test 2>&1 | Tee-Object -FilePath $FrontendTestLog
      $FrontendTestExitCode = $LASTEXITCODE
      if ($FrontendTestExitCode -ne 0) {
        $FrontendTestTail = ((Get-Content $FrontendTestLog -Tail 60) | ForEach-Object { $_.Trim() }) -join " | "
        if ($FrontendTestTail.Length -gt 7000) { $FrontendTestTail = $FrontendTestTail.Substring($FrontendTestTail.Length - 7000) }
        $FrontendTestAnnotation = $FrontendTestTail.Replace("%", "%25")
        Write-Output "::error title=Frontend test failure details::$FrontendTestAnnotation"
        throw "Frontend tests failed with code $FrontendTestExitCode"
      }
    }
    Run-Step "Frontend lint" { npm --prefix frontend run lint }
    Run-Step "Frontend dependency audit" { npm --prefix frontend audit --audit-level=high }
  }

  $EngineDist = Join-Path $Root "build\desktop\engine"
  $EngineWork = Join-Path $Root "build\desktop\pyinstaller-work"
  Remove-Item $EngineDist -Recurse -Force -ErrorAction SilentlyContinue
  Remove-Item $EngineWork -Recurse -Force -ErrorAction SilentlyContinue
  Run-Step "Build standalone engine" {
    & $Python -m PyInstaller --noconfirm --clean --distpath $EngineDist --workpath $EngineWork tools\desktop\HighlightStudioEngine.spec
  }
  $EngineExe = Join-Path $EngineDist "HighlightStudioEngine\HighlightStudioEngine.exe"
  Run-Step "Verify packaged engine version and startup" {
    $EngineVerifyLog = Join-Path $env:RUNNER_TEMP "highlight-studio-engine-verify.log"
    $SavedErrorActionPreference = $ErrorActionPreference
    try {
      $ErrorActionPreference = "Continue"
      & $Python tools\desktop\verify_engine_runtime.py $EngineExe "v$Version" --app-root $Root 2>&1 | Tee-Object -FilePath $EngineVerifyLog
      $EngineVerifyExitCode = $LASTEXITCODE
    } finally {
      $ErrorActionPreference = $SavedErrorActionPreference
    }
    if ($EngineVerifyExitCode -ne 0) {
      $EngineVerifyTail = ((Get-Content $EngineVerifyLog -Tail 60) | ForEach-Object { $_.ToString().Trim() }) -join " | "
      $EngineVerifyTail = $EngineVerifyTail.Replace("`r", " ").Replace("`n", " ")
      if ($EngineVerifyTail.Length -gt 7000) { $EngineVerifyTail = $EngineVerifyTail.Substring($EngineVerifyTail.Length - 7000) }
      $EngineVerifyAnnotation = $EngineVerifyTail.Replace("%", "%25")
      Write-Output "::error title=Packaged engine verification details::$EngineVerifyAnnotation"
      throw "Packaged engine verification failed with code $EngineVerifyExitCode"
    }
  }
  Run-Step "Sign standalone engine when certificate is configured" { & (Join-Path $PSScriptRoot "sign_engine.ps1") -EnginePath $EngineExe }
}

