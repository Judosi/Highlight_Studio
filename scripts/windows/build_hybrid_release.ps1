function Write-JsonUtf8([string]$Path, $Value) {
  $Json = $Value | ConvertTo-Json -Depth 8
  [System.IO.File]::WriteAllText($Path, $Json + [Environment]::NewLine, [System.Text.UTF8Encoding]::new($false))
}

function Get-ConfigValue($EnvironmentValue, $Existing, [string]$Name, $Fallback = "") {
  if (![string]::IsNullOrWhiteSpace([string]$EnvironmentValue)) { return $EnvironmentValue }
  if ($Existing -and $Existing.PSObject.Properties.Name -contains $Name) { return $Existing.$Name }
  return $Fallback
}

